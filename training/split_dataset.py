"""Split converted RDD2022 countries into train / val / test and write data.yaml.

Run from the repository root (after convert_voc_to_yolo.py):
    python -m training.split_dataset --countries India --name india
    python -m training.split_dataset --name all6           # every converted country

Only the annotated "train" folders of RDD2022 are used. The official "test"
folders have no labels, so they cannot be used to measure accuracy.

How the split works
  * Each country is split on its own, 80% train / 10% val / 10% test, with a
    fixed random seed. India's test images are therefore identical whether
    we train on India alone or on all countries, which keeps the Phase 7
    comparison fair.
  * Background images (no target boxes) are capped at 10% of each country's
    images. India has 58% background images after dropping non-target
    labels. Some background teaches the model that plain road is not damage
    (our fixed camera will mostly see undamaged road), but at 58% most of
    each epoch would be spent on images with nothing to detect. Ultralytics
    recommends 0-10% background images. The cap is applied the same way to
    train, val and test.

Writes, inside the gitignored dataset/yolo/ folder:
    splits/<Country>_train.txt, _val.txt, _test.txt   (one image path per line)
    <name>.yaml                                        (pass this to YOLO as data=)
"""

import argparse
import json
import random

from config import settings

CLASSES = ["D00", "D10", "D20", "D40"]
SEED = 42
TRAIN_FRAC, VAL_FRAC = 0.8, 0.1          # test gets the rest (0.1)
MAX_BACKGROUND_FRAC = 0.10
YOLO_DIR = settings.DATASET_DIR / "yolo"
REPORT_DIR = settings.PROJECT_ROOT / "training" / "reports"


def split_country(country):
    label_dir = YOLO_DIR / "labels" / country
    image_dir = YOLO_DIR / "images" / country
    stems = sorted(p.stem for p in label_dir.glob("*.txt"))   # sorted -> same result every run
    with_boxes = [s for s in stems if (label_dir / f"{s}.txt").read_text().strip()]
    background = [s for s in stems if s not in set(with_boxes)]

    rng = random.Random(f"{SEED}-{country}")
    # Largest number of backgrounds that keeps them at <= 10% of the total.
    max_bg = int(len(with_boxes) * MAX_BACKGROUND_FRAC / (1 - MAX_BACKGROUND_FRAC))
    background = sorted(rng.sample(background, min(max_bg, len(background))))

    # Split positives and backgrounds separately so every split gets the same mix.
    splits = {"train": [], "val": [], "test": []}
    for group in (with_boxes, background):
        group = group[:]
        rng.shuffle(group)
        n_train = round(len(group) * TRAIN_FRAC)
        n_val = round(len(group) * VAL_FRAC)
        splits["train"] += group[:n_train]
        splits["val"] += group[n_train:n_train + n_val]
        splits["test"] += group[n_train + n_val:]

    (YOLO_DIR / "splits").mkdir(parents=True, exist_ok=True)
    counts = {}
    bg_set = set(background)
    for split, items in splits.items():
        paths = [str(image_dir / f"{s}.jpg") for s in sorted(items)]
        (YOLO_DIR / "splits" / f"{country}_{split}.txt").write_text("\n".join(paths) + "\n")
        counts[split] = {"images": len(items), "background": sum(s in bg_set for s in items)}
    counts["background_available"] = len(stems) - len(with_boxes)
    counts["background_used"] = len(background)
    return counts


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--countries", nargs="+", default=None,
                        help="default: every country already converted")
    parser.add_argument("--name", required=True, help="dataset name, e.g. india or all6")
    args = parser.parse_args()
    countries = args.countries or sorted(p.name for p in (YOLO_DIR / "labels").iterdir() if p.is_dir())

    report = {c: split_country(c) for c in countries}
    for c, r in report.items():
        print(f"{c}: train {r['train']['images']}, val {r['val']['images']}, "
              f"test {r['test']['images']}  (background used {r['background_used']} "
              f"of {r['background_available']})")

    # data.yaml: absolute paths, because this file is generated per machine.
    def split_list(split):
        return "\n".join(f"  - {(YOLO_DIR / 'splits' / f'{c}_{split}.txt').as_posix()}" for c in countries)

    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(CLASSES))
    yaml_path = YOLO_DIR / f"{args.name}.yaml"
    yaml_path.write_text(
        f"# Generated by training/split_dataset.py: countries {', '.join(countries)}, seed {SEED}\n"
        f"path: {YOLO_DIR.as_posix()}\n"
        f"train:\n{split_list('train')}\nval:\n{split_list('val')}\ntest:\n{split_list('test')}\n"
        f"names:\n{names}\n"
    )
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / f"split_{args.name}.json").write_text(json.dumps(
        {"seed": SEED, "train_frac": TRAIN_FRAC, "val_frac": VAL_FRAC,
         "max_background_frac": MAX_BACKGROUND_FRAC, "countries": report}, indent=2))
    print(f"Wrote {yaml_path}")


if __name__ == "__main__":
    main()
